export function getMethodDefinition(methodKey: string): MethodDefinition | null {
  return METHODOLOGY_REGISTRY.find(m => m.method_key === methodKey) || null;
}

export function getMethodsByCategory(category: string): MethodDefinition[] {
  return METHODOLOGY_REGISTRY.filter(m => m.category === category);
}

export function getMethodKeys(): string[] {
  return METHODOLOGY_REGISTRY.map(m => m.method_key);
}