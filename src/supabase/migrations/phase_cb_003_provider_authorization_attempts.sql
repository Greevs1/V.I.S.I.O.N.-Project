-- Functions: PostgreSQL grants EXECUTE to PUBLIC on every new function, so each is
-- revoked from all four roles first, then granted to service_role ONLY.
-- REVOKE-then-GRANT lands on exactly {service_role: EXECUTE}; the reverse would
-- land on nothing and lock every caller out. Withholding the PUBLIC revoke would
-- expose the callback boundary and the cancel/fail surface to anon through
-- PostgREST.
