-- ============================================================================
-- VISION — CONNECTED BUSINESS
-- CB-003 — PROVIDER AUTHORIZATION ATTEMPTS
-- ============================================================================
-- The server-side boundary that a future provider authorization begins from.
-- It exists to make four classes of mistake UNREPRESENTABLE rather than merely
-- discouraged:
--
--   1. A callback deciding where a connection belongs. The attempt is bound to
--      (business_id, initiated_by_profile_id, provider, connection_category) at
--      creation, and consumption RETURNS that binding. The browser never gets to
--      supply any of it as authority.
--   2. A state value being replayed. Only a 64-lowercase-hex DIGEST
--      REPRESENTATION is ever stored or accepted; the unique constraint on it
--      makes a second creation with the same digest impossible, and consumption
--      moves the row out of 'pending' exactly once.
--   3. A stale attempt being completed. Consumability is decided by
--      expires_at > clock_timestamp() in the same statement that consumes it, so
--      a stale row cannot be resurrected by any status value.
--   4. A credential ending up attached to the wrong business. result_connection_id
--      is carried as ONE composite FK with business_id into
--      business_connections(id, business_id) — the CB-001 pattern — so a
--      Business A attempt is structurally incapable of referencing a Business B
--      connection, even for service_role.
--
-- WHAT THIS MIGRATION DOES NOT DO
--   • NO provider integration. No OAuth call, no Plaid Link, no QuickBooks
--     exchange, no webhook verification, no token exchange of any kind. CB-003
--     builds the boundary only; CB-004 begins the flows.
--   • NO credential material of ANY kind. No access_token, refresh_token,
--     public_token, authorization_code, client_secret, password or provider
--     plaintext column exists, and no Vault object is referenced.
--     A Plaid public_token is returned by a FUTURE completion flow and is
--     deliberately NOT storable here.
--   • NO raw OAuth state. The database never receives, stores, logs or returns
--     the raw state value — only its digest.
--   • NO write to business_facts / business_fact_evidence / business_fact_conflicts.
--     The Digital Twin fact freeze remains in force, and nothing here can promote
--     a fact. UNKNOWN != ZERO is untouched because CB-003 computes no metric.
--   • NO change to any CB-001 / CB-001.1 / CB-001.2 / CB-002 object. Nothing
--     certified earlier is altered, re-granted or re-created.
--   • NO Base44 shared Supabase connector. No runtime use of it, ever.
--
-- ── THE AUTHORIZATION MODEL, STATED PLAINLY ──────────────────────────────────
--   SERVICE ROLE IS CAPABILITY, NOT AUTHORIZATION. A PostgREST RPC executes as
--   service_role and cannot see which human asked. This table therefore stores
--   WHOSE authorization was begun, so that the completion path can RE-AUTHORIZE
--   that actor and business before any credential is accepted — instead of
--   trusting what the browser sent back.
--
--   The caller's obligation (unchanged, existing Security Kernel):
--       authenticateActor() -> authorizeBusinessAccess() -> permission to manage
--       connections -> provider_authorization_attempt_create() -> provider flow
--   and at completion:
--       digest the presented state -> provider_authorization_attempt_consume()
--       -> re-authorize the RETURNED business_id / initiated_by_profile_id
--       -> only then accept provider material and write the connection.
--
-- ── WHAT IS GENERATED, STORED, RETURNED AND COMPARED ─────────────────────────
--   THE RAW STATE AND THE STORED DIGEST ARE DIFFERENT REPRESENTATIONS OF
--   DIFFERENT VALUES. The two encodings below are FROZEN as the CB-003 contract
--   so that a future call site cannot blur them:
--
--     RAW STATE (generated by the backend in CB-004, not here) — the bearer
--     value that travels the provider round trip:
--       1. exactly 32 cryptographically secure random bytes (CSPRNG)
--       2. encoded as BASE64URL WITHOUT PADDING
--       3. therefore exactly 43 characters
--       4. unguessable, single-use, short-lived
--       5. handed to the provider, and NEVER sent to PostgreSQL
--
--     STORED state_hash — the only value this database ever receives:
--       6. SHA-256 over the UTF-8 bytes of the raw state string
--       7. encoded as LOWERCASE HEXADECIMAL
--       8. therefore exactly 64 characters
--       9. the ONLY value supplied to provider_authorization_attempt_create()
--          and to provider_authorization_attempt_consume()
--
--   43 unpadded base64url characters and 64 lowercase hex characters are
--   DISJOINT BY CONSTRUCTION, so VISION's canonical raw-state representation
--   cannot satisfy constraint state_hash_format: presenting a raw state where a
--   digest belongs is a REJECTION, not a silent write of a bearer value. That is
--   a property of VISION's canonical encoding — it is NOT a claim that no
--   arbitrary token could ever have 64-lowercase-hex shape.
--
--   WHAT THE DATABASE PROVES, AND WHAT IT DOES NOT. The constraint proves ONE
--   thing: that the supplied value has the REQUIRED DIGEST REPRESENTATION
--   (64 lowercase hex characters). It does NOT prove that the backend actually
--   computed SHA-256 over a raw state — no shape test can prove that, and a value
--   of arbitrary 64-lowercase-hex shape is still accepted. The invariant is
--   REPRESENTATIONAL, NOT CRYPTOGRAPHIC. The TRUSTED BACKEND BOUNDARY remains
--   responsible for computing the digest before calling these functions.
--
--   STORED HERE: state_hash only. Never the raw state.
--   RETURNED TO THE CALLBACK on consumption: the attempt's bound identity —
--   attempt_id, business_id, initiated_by_profile_id, provider,
--   connection_category, return_target. NOT the hash, NOT the nonce.
--   LOOKUP: by (provider, state_hash) — an equality probe on the unique index.
--   CONSTANT-TIME: no secret-dependent comparison happens in SQL at all. The
--   database never sees the raw value, so there is nothing there to compare in
--   constant time; the probe is on the digest, and the digest is not derivable
--   from anything an attacker can observe. The browser-facing comparison (if any)
--   belongs to the provider round-trip in CB-004, not to this boundary.
--   REPLAY PREVENTION: three independent layers — the unique constraint on
--   state_hash (a second creation of the same digest is impossible), the
--   status='pending' predicate in the consuming UPDATE (a consumed row can never
--   match again), and the expires_at predicate (a stale row is never consumable).
--
--   THE RAW STATE IS NOT RECOVERABLE FROM THIS TABLE, BY ANYONE, INCLUDING
--   service_role. A leaked row yields a digest, not a usable state value.
--
-- ── attempt_nonce ────────────────────────────────────────────────────────────
--   A database-generated UUID that gives each attempt an identity independent of
--   the digest. It is NOT a secret, NOT a bearer credential, NOT accepted as an
--   input parameter by any function, and NOT returned to a browser. It exists for
--   internal audit correlation. Certified: no function accepts it.
--
-- ── TRANSACTION SEMANTICS ────────────────────────────────────────────────────
--   Consumption is ONE statement:
--       UPDATE ... SET status='used', used_at=clock_timestamp()
--        WHERE provider=... AND state_hash=... AND status='pending'
--          AND expires_at > clock_timestamp()
--       RETURNING ...
--   so two concurrent consumers cannot both win: the loser blocks on the row
--   lock, re-evaluates the predicate against the committed row and matches
--   nothing. No caller implements this race itself.
--
-- ── ROLE-DEPENDENT SPEECH (deliberate, and not symmetric) ────────────────────
--   consume() is SILENT: it returns no rows for wrong, stale, spent, cancelled
--   or failed attempts, and NEVER raises. It is the callback entry point, so a
--   distinguishable error would be an oracle telling an unauthenticated caller
--   whether a state existed, was used, or had expired.
--   cancel()/fail() RAISE when nothing was cancellable, because they are called
--   by an already-authorized actor about their own attempt, where a real error is
--   the correct and useful answer.
--
-- ── VERIFIED TARGETS (probed live before writing, not assumed) ───────────────
--   business_entities(id uuid)                    — canonical business identity
--   profiles(id uuid)                             — canonical actor identity
--   business_connections(id, business_id) UNIQUE  — CB-001 same-business anchor
--   Vocabulary (provider, connection_category) mirrors
--   base44/shared/providers/vocabulary.ts PROVIDERS / CONNECTION_CATEGORIES, and
--   the static harness asserts the two stay equal.
--
-- ── ACL POSTURE (SEC-031 / SEC-032 are live debt — defaults are NOT trusted) ──
--   The project's pg_default_acl seeds a new relation with arwdDxtm for
--   service_role AT CREATE TIME, and a new FUNCTION with EXECUTE to PUBLIC. A
--   GRANT is only additive, so only an explicit REVOKE establishes the intended
--   set. For the table and for all four functions: REVOKE from PUBLIC, anon,
--   authenticated and service_role FIRST, then the single narrow GRANT. Order is
--   a correctness property; the reverse lands on nothing.
--   No DELETE is granted to any role: authorization attempts are provenance and
--   are retired by status, never destroyed by a normal lifecycle operation.
--
-- ── RETENTION (planned, deliberately NOT implemented here) ───────────────────
--   Attempts live 10 minutes. A future retention job (scheduled task or
--   reviewed migration, its own change) may retire rows older than 24 hours.
--   That job will need an explicit privilege decision — it is exactly the kind
--   of DELETE this migration withholds — so it is documented, not pre-granted.
--   Nothing in CB-003 depends on a scheduler, and nothing in CB-003 requires
--   deletion to stay correct.
--   'expired' is a DESCRIPTIVE marker a future sweep may set. Consumability
--   never depends on it: the guard reads expires_at directly, so a row left at
--   'pending' past its expiry is already unusable.
--
-- ── IDEMPOTENT / ATOMIC ─────────────────────────────────────────────────────
--   create table if not exists is idempotent; create or replace function is
--   idempotent; REVOKE/GRANT/ALTER OWNER are idempotent; every index is
--   IF NOT EXISTS. The whole file is ONE transaction.
--
-- ROLLBACK (safe only while no real authorization attempt is in flight)
--   -- begin;
--   --   drop function if exists public.provider_authorization_attempt_fail(uuid, uuid, text);
--   --   drop function if exists public.provider_authorization_attempt_cancel(uuid, uuid);
--   --   drop function if exists public.provider_authorization_attempt_consume(text, text);
--   --   drop function if exists public.provider_authorization_attempt_create(text, text, uuid, uuid, text, text);
--   --   drop table if exists public.provider_authorization_attempts;
--   -- commit;
-- ============================================================================

begin;

-- ============================================================================
-- 1. provider_authorization_attempts
-- ============================================================================
create table if not exists public.provider_authorization_attempts (
  id                        uuid primary key default gen_random_uuid(),

  -- Provider-neutral vocabulary, identical to CB-001's connection vocabulary.
  provider                  text not null,
  connection_category       text not null,

  -- The canonical identities this attempt is permanently bound to. business_id is
  -- the existing business identity; initiated_by_profile_id is the existing
  -- profiles.id actor identity. No second user system is created.
  business_id               uuid not null references public.business_entities(id) on delete cascade,
  initiated_by_profile_id   uuid null references public.profiles(id) on delete set null,

  -- DIGEST ONLY. 64 lowercase hex characters = SHA-256 hex. The raw state is
  -- never accepted, stored, logged or returned.
  state_hash                text not null,

  status                    text not null default 'pending',

  -- Safe INTERNAL application path only. See the invariant constraint below.
  return_target             text not null,

  created_at                timestamptz not null default now(),
  -- 10 minutes after creation, exactly. Enforced by constraint, not convention.
  expires_at                timestamptz not null default (now() + interval '10 minutes'),

  used_at                   timestamptz null,

  -- Populated only after a successful consumption, and only with a connection
  -- belonging to the SAME business. See the composite FK below.
  result_connection_id      uuid null,

  -- Shape only — a bounded, lower_snake token. The provider-specific vocabulary of
  -- failure classes belongs to the phase that produces them, so none is invented
  -- here. Never carries provider detail: it is a CLASS, not a message.
  failure_class             text null,

  -- Independent attempt identity for audit correlation. Not a secret, never an
  -- input parameter, never returned to a browser.
  attempt_nonce             uuid not null default gen_random_uuid(),

  -- ── vocabulary ────────────────────────────────────────────────────────────
  -- Deliberate CHECK allowlists, exactly as CB-001 chose, mirroring
  -- base44/shared/providers/vocabulary.ts. This is the SINGLE source of truth for
  -- the vocabulary in the database: the functions do NOT re-encode the list, so
  -- the two can never disagree. Adding a provider is a one-line constraint swap.
  constraint provider_authorization_attempts_provider_check
    check (provider in ('quickbooks', 'plaid')),
  constraint provider_authorization_attempts_category_check
    check (connection_category in ('accounting', 'banking', 'payroll', 'crm', 'other')),

  constraint provider_authorization_attempts_status_check
    check (status in ('pending', 'used', 'expired', 'failed', 'cancelled')),

  -- ── the digest invariant ──────────────────────────────────────────────────
  -- The database accepts only VISION's canonical DIGEST REPRESENTATION: 64
  -- lowercase hex characters. The canonical raw-state representation is
  -- 43-character unpadded base64url (32 random bytes) and therefore cannot
  -- satisfy this column's 64-lowercase-hex constraint — the two representations
  -- are disjoint by construction, so presenting a raw state where a digest
  -- belongs is a rejection rather than a silent write of a bearer value.
  -- This proves REPRESENTATION, not provenance: it cannot prove the backend
  -- computed SHA-256, and a value of arbitrary 64-lowercase-hex shape is still
  -- accepted. The backend remains responsible for computing SHA-256 before
  -- calling these functions. See the encoding contract in the file header.
  constraint provider_authorization_attempts_state_hash_format
    check (state_hash ~ '^[0-9a-f]{64}$'),

  -- ── the return_target invariant (open-redirect prevention) ────────────────
  -- Deterministic and total: a return target is an INTERNAL ABSOLUTE PATH, or it
  -- is rejected. There is no allow-list to drift and no parser to disagree with,
  -- because every bypass class is excluded structurally:
  --   must start with '/'            — a path, not a free-form URL
  --   must not start with '//'       — protocol-relative (//evil.example)
  --   no ':' anywhere                — removes every scheme (http:, https:,
  --                                    javascript:, data:) AND the userinfo trick
  --   no '\'                         — removes backslash/normalisation tricks
  --   no '%'                         — removes percent-encoded and
  --                                    double-encoded bypasses of the rules above
  --   no '..'                        — removes traversal
  --   no control characters          — removes CR/LF and header-injection shapes
  --   length 1..512                  — bounded
  -- Enforced at the DATABASE boundary so a future call site cannot forget it.
  constraint provider_authorization_attempts_return_target_check
    check (
      return_target like '/%'
      and return_target not like '//%'
      and length(return_target) between 1 and 512
      and position(':' in return_target) = 0
      and position(chr(92) in return_target) = 0
      and position('%' in return_target) = 0
      and position('..' in return_target) = 0
      and return_target !~ '[[:cntrl:]]'
    ),

  -- ── the expiry invariant ──────────────────────────────────────────────────
  -- Exactly ten minutes, for every row, regardless of who writes it. A longer
  -- lived attempt is unrepresentable rather than merely discouraged.
  constraint provider_authorization_attempts_expiry_shape
    check (expires_at = created_at + interval '10 minutes'),

  constraint provider_authorization_attempts_failure_class_shape
    check (failure_class is null
           or (length(failure_class) between 1 and 64 and failure_class ~ '^[a-z][a-z0-9_]*$')),

  -- ── lifecycle shape: a terminal state carries its evidence ────────────────
  --   pending   : nothing has happened yet, and the initiator MUST be known —
  --               an attempt with no attributable actor is not creatable, which
  --               is also why a consumed attempt always returns a non-null actor.
  --   used      : exactly one consumption, stamped.
  --   failed    : a bounded failure class, and never a consumption.
  --   cancelled : never consumed, never connected.
  --   expired   : never consumed.
  --   plus: a connection may only ever attach to a CONSUMED attempt, so
  --   "authorize, then consume, then attach" cannot be reordered.
  constraint provider_authorization_attempts_lifecycle_shape
    check (
      (status <> 'pending'   or (used_at is null and result_connection_id is null and failure_class is null))
      and (status <> 'pending'   or initiated_by_profile_id is not null)
      and (status <> 'used'      or used_at is not null)
      and (status <> 'failed'    or (failure_class is not null and used_at is null))
      and (status <> 'cancelled' or (used_at is null and result_connection_id is null))
      and (status <> 'expired'   or used_at is null)
      and (result_connection_id is null or status = 'used')
    ),

  -- ── replay prevention, layer 1 ────────────────────────────────────────────
  -- One row per digest, ever. Also the callback's lookup index.
  constraint provider_authorization_attempts_state_hash_unique
    unique (state_hash),

  -- ── SAME-BUSINESS RESULT INTEGRITY (structural, not application-enforced) ──
  -- The CB-001 composite-FK pattern. (result_connection_id, business_id) is ONE
  -- foreign key into business_connections(id, business_id), so an attempt for
  -- Business A is STRUCTURALLY INCAPABLE of recording a Business B connection —
  -- rejected by the database even for service_role, and even if application code
  -- is wrong.
  -- MATCH SIMPLE: while result_connection_id is NULL the constraint is vacuously
  -- satisfied, which is every attempt until it completes.
  -- ON DELETE CASCADE matches provider_credentials exactly: attempt rows are
  -- short-lived (10 minutes / 24h retention) and are provenance ABOUT a
  -- connection. This also keeps a business deletable — with NO ACTION, a business
  -- deletion cascading into business_connections would be blocked by an old
  -- attempt row. No runtime role holds DELETE anywhere, so the only ways a
  -- connection disappears are a business cascade or a superuser action.
  constraint provider_authorization_attempts_result_connection_same_business_fkey
    foreign key (result_connection_id, business_id)
    references public.business_connections (id, business_id) on delete cascade
);

-- Indexes: only the three query paths that actually exist.
--   • a business's own attempts, by state       → (business_id, status)
--   • an actor's attempts (self-inspection)     → (initiated_by_profile_id)
--   • the future expiry/retention sweep         → (expires_at) where pending
-- The two UNIQUE constraints already index id and state_hash and are not
-- duplicated here.
create index if not exists provider_authorization_attempts_business_status_idx
  on public.provider_authorization_attempts (business_id, status);
create index if not exists provider_authorization_attempts_profile_idx
  on public.provider_authorization_attempts (initiated_by_profile_id);
create index if not exists provider_authorization_attempts_expiry_idx
  on public.provider_authorization_attempts (expires_at)
  where status = 'pending';

-- ============================================================================
-- 2. provider_authorization_attempt_create
-- ============================================================================
-- Begins an authorization. Records the digest and the permanent binding.
-- Returns ONLY the attempt id — never the digest, never the nonce.
--
-- The vocabulary and the invariants (provider, connection_category, state_hash
-- shape, return_target shape, expiry) are enforced by the table's CHECK
-- constraints, deliberately in ONE place rather than duplicated in the function.
-- A malformed provider, a raw state value in VISION's canonical 43-character
-- representation, or an external return target is therefore rejected by the
-- DATABASE, not by this function's good intentions. (The database proves the
-- digest REPRESENTATION only — the backend remains responsible for computing
-- SHA-256 before calling.)
create or replace function public.provider_authorization_attempt_create(
  p_provider                text,
  p_connection_category     text,
  p_business_id             uuid,
  p_initiated_by_profile_id uuid,
  p_state_hash              text,
  p_return_target           text
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_attempt_id uuid := gen_random_uuid();
  -- ONE timestamp for both columns, so the ten-minute invariant holds exactly.
  -- now() would also be transaction-stable, but naming it makes the invariant
  -- explicit rather than incidental.
  v_now        timestamptz := now();
begin
  if p_business_id is null or p_initiated_by_profile_id is null then
    raise exception 'provider_authorization_attempt_create: business_id and initiated_by_profile_id are required'
      using errcode = '22023';
  end if;
  if p_provider is null or p_connection_category is null
     or p_state_hash is null or p_return_target is null then
    raise exception 'provider_authorization_attempt_create: provider, connection_category, state_hash and return_target are required'
      using errcode = '22023';
  end if;

  insert into public.provider_authorization_attempts
    (id, provider, connection_category, business_id, initiated_by_profile_id,
     state_hash, status, return_target, created_at, expires_at)
  values
    (v_attempt_id, p_provider, p_connection_category, p_business_id, p_initiated_by_profile_id,
     p_state_hash, 'pending', p_return_target, v_now, v_now + interval '10 minutes');

  return v_attempt_id;
end;
$$;

alter function public.provider_authorization_attempt_create(text, text, uuid, uuid, text, text) owner to postgres;

-- ============================================================================
-- 3. provider_authorization_attempt_consume   — the atomic completion step
-- ============================================================================
-- Consumes the attempt EXACTLY ONCE and returns the identity it was bound to.
--
-- ADDRESSED BY (provider, digest) ONLY. No attempt id, no business id, no actor
-- id is accepted: a caller cannot choose WHOSE attempt it is completing, so a
-- browser-supplied business_id has no parameter to travel through.
--
-- IT RETURNS NO ROWS WHEN NOTHING IS CONSUMABLE, and NEVER RAISES. A caller
-- cannot distinguish wrong digest, stale, spent, cancelled or failed — so this
-- is not an existence or state oracle for an unauthenticated callback.
--
-- THE RETURNED business_id / initiated_by_profile_id ARE THE AUTHORITY for what
-- follows: the completion path must RE-AUTHORIZE them. Because a pending row
-- always has a non-null initiator (lifecycle CHECK) and consumption only ever
-- proceeds from 'pending', a successful consumption always yields a non-null
-- initiated_by_profile_id.
--
-- IT NEVER READS OR RETURNS THE NONCE, and it writes nothing but status/used_at.
create or replace function public.provider_authorization_attempt_consume(
  p_provider   text,
  p_state_hash text
)
returns table (
  attempt_id              uuid,
  business_id             uuid,
  initiated_by_profile_id uuid,
  provider                text,
  connection_category     text,
  return_target           text
)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_provider is null or p_state_hash is null then
    return;
  end if;

  -- ONE statement. The row lock makes this race-safe: a concurrent consumer
  -- blocks, then re-evaluates the predicate against the updated row, whose status
  -- is no longer 'pending' — so it matches nothing and returns no rows.
  -- Expiry is judged HERE, at call time, so a stale row cannot be resurrected by
  -- any stored status value.
  return query
  update public.provider_authorization_attempts a
     set status = 'used',
         used_at = clock_timestamp()
   where a.provider = p_provider
     and a.state_hash = p_state_hash
     and a.status = 'pending'
     and a.expires_at > clock_timestamp()
  returning a.id,
            a.business_id,
            a.initiated_by_profile_id,
            a.provider,
            a.connection_category,
            a.return_target;
end;
$$;

alter function public.provider_authorization_attempt_consume(text, text) owner to postgres;

-- ============================================================================
-- 4. provider_authorization_attempt_cancel
-- ============================================================================
-- Abandons a pending attempt on purpose. BOUND to the business, so knowing an
-- attempt id is not enough to act on someone else's attempt.
--
-- The ROW IS NEVER DELETED: abandonment is provenance, and no role holds DELETE.
-- Reaches the 'cancelled' state only from 'pending', so a consumed attempt can
-- never be un-consumed by cancellation.
-- RAISES when nothing was cancellable — this is an authorized actor's own
-- attempt, where a real error is the correct answer (see the header asymmetry).
create or replace function public.provider_authorization_attempt_cancel(
  p_attempt_id  uuid,
  p_business_id uuid
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_attempt_id is null or p_business_id is null then
    raise exception 'provider_authorization_attempt_cancel: attempt and business are required'
      using errcode = '22023';
  end if;

  update public.provider_authorization_attempts
     set status = 'cancelled'
   where id = p_attempt_id
     and business_id = p_business_id
     and status = 'pending';

  if not found then
    raise exception 'provider_authorization_attempt_cancel: no cancellable attempt for this business'
      using errcode = '42501';
  end if;
end;
$$;

alter function public.provider_authorization_attempt_cancel(uuid, uuid) owner to postgres;

-- ============================================================================
-- 5. provider_authorization_attempt_fail
-- ============================================================================
-- Records a bounded failure class on a pending attempt. Same business binding and
-- the same "never from a consumed attempt" rule as cancel(). Makes the 'failed'
-- state reachable through an intended surface rather than only by direct SQL,
-- while keeping the class free of provider detail — a class, never a message, and
-- never a token.
create or replace function public.provider_authorization_attempt_fail(
  p_attempt_id    uuid,
  p_business_id   uuid,
  p_failure_class text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_attempt_id is null or p_business_id is null or p_failure_class is null then
    raise exception 'provider_authorization_attempt_fail: attempt, business and failure_class are required'
      using errcode = '22023';
  end if;

  update public.provider_authorization_attempts
     set status = 'failed',
         failure_class = p_failure_class
   where id = p_attempt_id
     and business_id = p_business_id
     and status = 'pending';

  if not found then
    raise exception 'provider_authorization_attempt_fail: no failable attempt for this business'
      using errcode = '42501';
  end if;
end;
$$;

alter function public.provider_authorization_attempt_fail(uuid, uuid, text) owner to postgres;

-- ============================================================================
-- 6. LOCKDOWN — REVOKE FIRST, THEN THE ONE NARROW GRANT
-- ============================================================================
-- RLS is enabled explicitly (never left to the rls_auto_enable event trigger) and
-- NO policies are created, so anon/authenticated are denied by the grant layer
-- AND by the absence of any policy.
--
-- service_role is REVOKED first because pg_default_acl already materialised
-- arwdDxtm into relacl at CREATE TABLE time. GRANT is additive, so only this
-- REVOKE establishes the intended set. DELETE is deliberately NOT granted:
-- attempts are provenance.
--
-- postgres (the owner) is deliberately not touched: owner privileges are implicit
-- and survive any ACL edit.
alter table public.provider_authorization_attempts enable row level security;

revoke all on table public.provider_authorization_attempts from public;
revoke all on table public.provider_authorization_attempts from anon;
