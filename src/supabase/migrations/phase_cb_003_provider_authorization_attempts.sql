comment on table public.provider_authorization_attempts is
  'CB-003 — server-side authorization-attempt boundary for future provider connection flows. Stores a state DIGEST only: never a raw OAuth state, never an access/refresh/public token, never an authorization code or client secret. Bound to (business_id, initiated_by_profile_id, provider, connection_category) at creation; consumption returns that binding so the completion path re-authorizes from the attempt rather than from the browser.';
comment on column public.provider_authorization_attempts.state_hash is
  'VISION canonical DIGEST REPRESENTATION: lowercase hexadecimal of SHA-256 over the UTF-8 bytes of the raw state, exactly 64 characters. The canonical raw state is 32 random bytes encoded as 43-character unpadded base64url — a different representation of a different value, generated by the backend, sent to the provider, and NEVER given to this database. The two representations are disjoint by construction, so a raw state cannot satisfy provider_authorization_attempts_state_hash_format. This column proves the digest REPRESENTATION only: it cannot prove that the backend computed SHA-256, and a value of arbitrary 64-lowercase-hex shape is still accepted. Not recoverable to the raw state by any role. Unique, so a digest can be created once.';
comment on column public.provider_authorization_attempts.attempt_nonce is
  'Internal audit-correlation identity. NOT a secret, NOT a bearer credential, NOT accepted as an input by any function and NOT returned to a browser. Never used for lookup.';
comment on column public.provider_authorization_attempts.return_target is
  'Safe INTERNAL application path only. Enforced by provider_authorization_attempts_return_target_check: must begin with /, must not begin with //, and may contain no : \ % or .. and no control character. Rejects http/https/javascript/data schemes, protocol-relative targets, backslash and percent-encoding bypasses, and traversal.';
comment on column public.provider_authorization_attempts.result_connection_id is
  'Set only after consumption, and only to a connection of the SAME business — enforced structurally by provider_authorization_attempts_result_connection_same_business_fkey over (result_connection_id, business_id) → business_connections(id, business_id). A cross-business attachment is unrepresentable even for service_role.';
comment on column public.provider_authorization_attempts.failure_class is
  'Bounded lower_snake failure CLASS (not a message, never provider detail, never a token). The provider-specific vocabulary belongs to the phase that produces the failures.';

