-- ============================================================================
-- PRODUCTION GATES THAT THIS MIGRATION DOES NOT OPEN
-- ============================================================================
--   1. NO PROVIDER FLOW. CB-003 creates the boundary only. Plaid Link, the
--      QuickBooks exchange, Plaid webhook authenticity and token storage are all
--      later phases and none of them is started here.
--   2. CALL-SITE AUTHORIZATION. This table records whose authorization began; it
--      cannot perform authorization. Every call site must still run the Security
--      Kernel sequence and must derive business_id / connection_id server-side.
--   3. ROOT KEY / REAL CREDENTIALS. No real provider credential may be stored
--      until Vault root-key custody is confirmed and the credential wrappers are
--      exercised against a real flow. CB-003 stores no credential at all.
--   4. RETENTION. Purging attempts older than 24 hours is a separate change that
--      requires an explicit DELETE privilege decision. It is documented, not
--      granted, and nothing in CB-003 depends on it.
-- ============================================================================